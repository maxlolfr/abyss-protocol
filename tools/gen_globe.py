def xy(lat, lon):
    return ((lon + 180.0) / 360.0 * W, (90.0 - lat) / 180.0 * H)


def poly_points(pts):
    out = []
    prev = None
    for lat, lon in pts:
        if prev is not None and lon - prev > 180:
            lon -= 360
        elif prev is not None and prev - lon > 180:
            lon += 360
        out.append(xy(lat, lon))
        prev = lon
    return out


def main(dst):
    mask = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(mask)
    for name, pts in LANDS.items():
        p = [xy(a, b) for a, b in pts] if name == "antarctique" else poly_points(pts)
        for shift in (-W, 0, W):
            d.polygon([(x + shift, y) for x, y in p], fill=255)
    land = np.array(mask) > 127
    # distance à la côte (en pixels ≈ 19,5 km) → bathymétrie stylisée
    dist = ndimage.distance_transform_edt(~land)
    rng = np.random.default_rng(7)
    noise = ndimage.gaussian_filter(rng.standard_normal((H, W)), 9) * 6 + ndimage.gaussian_filter(rng.standard_normal((H, W)), 3) * 2
    depth = np.clip((dist + noise * 3) / 60.0, 0, 1)  # 0 côte → 1 plaine abyssale
    shelf = np.clip(1.0 - (dist + noise) / 13.0, 0, 1) ** 1.5
    c_shelf = np.array([26, 92, 110], float)
    c_mid = np.array([13, 56, 78], float)
    c_deep = np.array([6, 24, 40], float)
    ocean = c_mid[None, None] * (1 - depth[..., None]) + c_deep[None, None] * depth[..., None]
    ocean = ocean * (1 - shelf[..., None]) + c_shelf[None, None] * shelf[..., None]
    # dorsales et fosses
    tr = Image.new("L", (W, H), 0)
    td = ImageDraw.Draw(tr)
    import math
    for lat, lon, km, az in TRENCHES:
        pts = []
        for s in np.linspace(-0.5, 0.5, 24):
            dd = km * s / 6371.0
            br = math.radians(az)
            la, lo = math.radians(lat), math.radians(lon)
            la2 = math.asin(math.sin(la) * math.cos(dd) + math.cos(la) * math.sin(dd) * math.cos(br))
            lo2 = lo + math.atan2(math.sin(br) * math.sin(dd) * math.cos(la), math.cos(dd) - math.sin(la) * math.sin(la2))
            pts.append((math.degrees(la2), (math.degrees(lo2) + 540) % 360 - 180))
        pts = poly_points(pts)
        for shift in (-W, 0, W):
            td.line([(x + shift, y) for x, y in pts], fill=255, width=12)
    trench = np.array(tr.filter(ImageFilter.GaussianBlur(5))) / 255.0
    ocean = ocean * (1 - trench[..., None] * 0.9) + np.array([1, 4, 10], float)[None, None] * trench[..., None] * 0.9
    # terres : métal sombre, relief bruité, liseré cyan
    relief = ndimage.gaussian_filter(rng.standard_normal((H, W)), 4) * 10 + ndimage.gaussian_filter(rng.standard_normal((H, W)), 1.2) * 4
    inland = np.clip(ndimage.distance_transform_edt(land) / 18.0, 0, 1)
    c_land = np.array([44, 54, 62], float) * (1 - inland[..., None] * 0.35) + relief[..., None]
    ice = np.zeros((H, W))
    ice[:int(H * 0.06)] = 1
    ice[int(H * 0.87):] = 1
    c_land = c_land * (1 - ice[..., None] * 0.5) + np.array([96, 112, 124], float)[None, None] * ice[..., None] * 0.3
    img = np.where(land[..., None], c_land, ocean)
    edge = (dist > 0) & (dist < 2.2)
    glow = np.clip(1.0 - dist / 5.0, 0, 1) * (~land)
    img = img + glow[..., None] * np.array([20, 90, 105], float)[None, None] * 0.55
    img[edge] = img[edge] * 0.3 + np.array([70, 205, 230], float) * 0.7
    Image.fromarray(np.clip(img, 0, 255).astype(np.uint8)).save(dst + "/earth.jpg", quality=90)
    # masque terre/mer (rouge) pour le rendu (reflets océan, nuit)
    Image.fromarray((land * 255).astype(np.uint8)).resize((1024, 512), Image.BILINEAR).save(dst + "/earth_mask.png")


